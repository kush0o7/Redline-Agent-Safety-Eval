#!/usr/bin/env python3
"""Generate a starter .env for a self-hosted Redline install.

Copies .env.example and fills in fresh secrets:
  - ADMIN_API_KEY         (random 32-byte hex)
  - FIELD_ENCRYPTION_KEY  (Fernet key: urlsafe base64 of 32 random bytes)
  - REDLINE_ENV=production

Standard library only, so it runs before any dependencies are installed.
Refuses to overwrite an existing .env unless --force is given.

Usage:  python scripts/init_env.py [--force] [--output PATH]
"""
from __future__ import annotations

import argparse
import base64
import os
import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generate_fernet_key() -> str:
    return base64.urlsafe_b64encode(os.urandom(32)).decode()


def render_env(template: str, admin_key: str, fernet_key: str) -> str:
    values = {
        "ADMIN_API_KEY": admin_key,
        "FIELD_ENCRYPTION_KEY": fernet_key,
        "REDLINE_ENV": "production",
    }
    out_lines = []
    seen: set[str] = set()
    for line in template.splitlines():
        m = re.match(r"^\s*#?\s*([A-Z_]+)=", line)
        if m and m.group(1) in values and m.group(1) not in seen:
            key = m.group(1)
            out_lines.append(f"{key}={values[key]}")
            seen.add(key)
        else:
            out_lines.append(line)
    missing = [k for k in values if k not in seen]
    if missing:
        out_lines.append("")
        out_lines.append("# ── Generated by scripts/init_env.py ──")
        out_lines.extend(f"{k}={values[k]}" for k in missing)
    return "\n".join(out_lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true", help="overwrite an existing .env")
    parser.add_argument("--output", default=str(ROOT / ".env"))
    parser.add_argument("--template", default=str(ROOT / ".env.example"))
    args = parser.parse_args(argv)

    out = Path(args.output)
    if out.exists() and not args.force:
        print(f"{out} already exists — not overwriting (use --force to replace it).", file=sys.stderr)
        return 1

    template = Path(args.template).read_text()
    content = render_env(template, secrets.token_hex(32), generate_fernet_key())
    out.write_text(content)
    try:
        os.chmod(out, 0o600)
    except OSError:
        pass
    print(f"Wrote {out} with a fresh ADMIN_API_KEY and FIELD_ENCRYPTION_KEY.")
    print("Next: set your model provider and judge in it, then run `docker compose up --build`.")
    print("Your admin key is in the file (ADMIN_API_KEY) — the UI and API need it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
